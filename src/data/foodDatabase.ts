// 영양정보는 계속 미확인(0). 앱의 개인 학습값/포장지 날짜 등록 흐름은 별도다.
type ShelfLifeSeed = [string, number, number, StorageType?];
function approximateFoods(category: FoodCategory, defaultStorage: StorageType, foods: ShelfLifeSeed[]): FoodDbEntry[] {
  return foods.map(([standardName, shelfLifeUnopenedDays, shelfLifeOpenedDays, storage]) => ({
    standardName, synonyms: [], category, defaultStorage: storage ?? defaultStorage,
    shelfLifeUnopenedDays, shelfLifeOpenedDays, unit: '개', icon: '🛒',
    nutrition: { calories: 0, protein: 0, fat: 0, carbs: 0 }, consumptionPattern: '비주기형',
  }));
}

